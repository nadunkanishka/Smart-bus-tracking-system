// Copies the design system into every app and generates the admin's CSS tokens.  Run: node shared/sync.js
import { copyFileSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { THEMES, RADII, SPACE, TYPE, SHADOWS } from './tokens.js';
import { LIVERIES, SCENES, VEHICLES, pick } from './vehicleShapes.js';

const here = dirname(fileURLToPath(import.meta.url));
const apps = join(here, '..', 'apps');
const put = (from, to) => { mkdirSync(dirname(to), { recursive: true }); copyFileSync(join(here, from), to); console.log('→', to.replace(join(here, '..'), '')); };

// Self-check: every image the lookup can ask for was baked (run `node shared/buses/export.mjs` if this fails).
const baked = join(here, 'buses/out');
const wanted = new Set(SCENES.map((sc) => `scene-${sc}`));
for (const name of VEHICLES) for (const livery of LIVERIES) for (const status of [undefined, 'idle', 'maint', 'off']) for (const running of [false, true]) wanted.add(pick(name, { livery, status, running }).key);
for (const key of wanted) if (!existsSync(join(baked, `${key}.webp`))) throw new Error(`Missing baked image "${key}.webp"`);
const copyImages = (to) => { rmSync(to, { recursive: true, force: true }); mkdirSync(to, { recursive: true }); for (const f of readdirSync(baked)) copyFileSync(join(baked, f), join(to, f)); console.log('→', to.replace(join(here, '..'), ''), `(${readdirSync(baked).length} images)`); };

for (const app of ['passenger-app', 'driver-app']) {
  copyImages(join(apps, app, 'assets/buses'));
  // Everything generated lands in src/shared/, so hand-written app code never sits next to a copy.
  const dest = join(apps, app, 'src/shared');
  put('native/busImages.js', join(dest, 'busImages.js'));
  put('busMarkers.js', join(dest, 'busMarkers.js'));
  put('tokens.js', join(dest, 'theme.js'));
  put('navIcons.js', join(dest, 'navIcons.js'));
  put('vehicleShapes.js', join(dest, 'vehicleShapes.js'));
  put('native/themeRuntime.js', join(dest, 'themeRuntime.js'));
  put('native/ui.js', join(dest, 'ui.js'));
  put('native/icons.js', join(dest, 'icons.js'));
  put('native/LiveMap.js', join(dest, 'LiveMap.js'));
  put('native/LiveMap.native.js', join(dest, 'LiveMap.native.js'));
  put('native/api.js', join(dest, 'api.js'));
  writeFileSync(join(dest, 'README.md'), '# Generated files\n\nEverything in this folder is copied from `shared/` at the repository root by `node shared/sync.js`.\nDo not edit these files here: change the source in `shared/` and run the sync again.\n');
}
const admin = join(apps, 'admin-dashboard/src/design');
put('vehicleShapes.js', join(admin, 'vehicleShapes.js'));
put('web/Vehicle.js', join(admin, 'Vehicle.js'));
put('web/busImages.js', join(admin, 'busImages.js'));
put('navIcons.js', join(admin, 'navIcons.js'));
put('busMarkers.js', join(admin, 'busMarkers.js'));
copyImages(join(admin, 'buses'));

const kebab = (s) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);
const shadow = (s, rgb, boost) => `0 ${s.shadowOffset.height}px ${s.shadowRadius}px rgba(${rgb}, ${Math.min(1, +(s.shadowOpacity * boost).toFixed(2))})`;
const legacyKey = /^(bg[A-Z]|border|text|accentOrange|accentBlue|accentDark|successLight|warningLight|dangerLight|black)/;
// The colour variables for one mode (strings and the tint pairs).
const colourVars = (c) => [
  ...Object.entries(c).filter(([k, v]) => typeof v === 'string' && !legacyKey.test(k)).map(([k, v]) => `  --${kebab(k)}: ${v};`),
  ...Object.entries(c.tints).flatMap(([k, [a, b]]) => [`  --tint-${k}-from: ${a};`, `  --tint-${k}-to: ${b};`]),
  ...Object.entries(c.tintLines).map(([k, v]) => `  --tint-line-${k}: ${v};`),
];
const shadowVars = (rgb, boost) => Object.entries(SHADOWS).map(([k, v]) => `  --shadow-${k}: ${shadow(v, rgb, boost)};`);
const darkBlock = [...colourVars(THEMES.dark), ...shadowVars('0, 0, 0', 3), '  color-scheme: dark;'];
const lines = [
  '/* GENERATED by shared/sync.js from shared/tokens.js — do not edit by hand. */',
  ':root {',
  ...colourVars(THEMES.light),
  ...Object.entries(RADII).map(([k, v]) => `  --radius-${k}: ${v}px;`),
  ...Object.entries(SPACE).map(([k, v]) => `  --space-${k}: ${v}px;`),
  ...shadowVars('21, 20, 15', 1),
  ...Object.entries(TYPE).flatMap(([k, t]) => [
    `  --fs-${kebab(k)}: ${t.fontSize}px;`, `  --lh-${kebab(k)}: ${t.lineHeight}px;`, `  --fw-${kebab(k)}: ${t.fontWeight};`,
  ]),
  '  --ease-out: cubic-bezier(0.23, 1, 0.32, 1);',
  '  --touch: 44px;',
  '  color-scheme: light;',
  '}',
  // Dark follows the system unless the app sets data-theme; data-theme always wins.
  '@media (prefers-color-scheme: dark) {',
  '  :root:not([data-theme="light"]) {',
  ...darkBlock.map((l) => `  ${l}`),
  '  }',
  '}',
  ':root[data-theme="dark"] {',
  ...darkBlock,
  '}',
];
writeFileSync(join(admin, 'tokens.css'), lines.join('\n') + '\n');
console.log('→ admin tokens.css');
